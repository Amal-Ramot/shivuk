def classify(name, qty=0, unit=""):
    """מחזיר שם קטגוריה (סוג מוצר). אם אין התאמה — '~' + המילה המשמעותית הראשונה.
    qty/unit (כמות בגרם/מ"ל) עוזרים להבחין למשל בין צ'יפס חטיף לצ'יפס קפוא."""
    cat = _classify(name)
    # צ'יפס באריזה גדולה (600 גרם ומעלה) הוא צ'יפס קפוא לטיגון/לתנור, לא חטיף
    # (מארז של שקיות קטנות, כמו "32*45 גרם", הוא עדיין חטיף)
    if cat == "צ'יפס" and unit == "g" and qty >= 600 and not re.search(r"\d\s*[*xX×]\s*\d", name or ""):
        return "צ'יפס קפוא"
    return cat


_FLAVOR = re.compile(r"(?<![א-ת])(?:(?:בטעמ|בטעמי|טעמ)(?![א-ת])|ט\.).*$")


def _classify(name):
    n = normalize(name)
    # "צ'יפס בטעם שמנת" הוא צ'יפס — הטעם לא קובע את סוג המוצר
    head = _FLAVOR.sub("", n).strip()
    if len(head) >= 3:
        n = head
    for cat, pats in _COMPILED:
        for p in pats:
            if p.search(n):
                for sub, spats in _SUB_COMPILED.get(cat, ()):
                    if any(sp.search(n) for sp in spats):
                        return sub
                return cat
    words = [w for w in _PUNCT.sub(" ", _SPACE.sub(" ", name or "")).split() if len(w) > 1 and not w.isdigit() and w not in _STOP]
    return "~" + (words[0] if words else "אחר")
